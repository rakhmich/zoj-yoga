/**
 * Получить статью по её ID
 * @param {string} id
 * @returns {Object|undefined}
 */
export function getArticleById(id) {
  return FITNESS_ARTICLES.find(article => article.id === id);
}

/**
 * Фильтрация статей по категории
 * @param {string} categoryId ('all' | 'physiology' | 'training' | 'recovery')
 * @returns {Array<Object>}
 */
export function getArticlesByCategory(categoryId = 'all') {
  if (!categoryId || categoryId === 'all') {
    return FITNESS_ARTICLES;
  }
  return FITNESS_ARTICLES.filter(article => article.category === categoryId);
}

/**
 * Полнотекстовый поиск по статьям
 * @param {string} query
 * @returns {Array<Object>}
 */
export function searchArticles(query) {
  if (!query || !query.trim()) return FITNESS_ARTICLES;
  const q = query.toLowerCase().trim();
  return FITNESS_ARTICLES.filter(article =>
    article.title.toLowerCase().includes(q) ||
    article.subtitle.toLowerCase().includes(q) ||
    article.tags.some(t => t.toLowerCase().includes(q))
  );
}